import sys
import xml.etree.ElementTree as ET

STAGE_ENUM = "VkPipelineStageFlagBits2"
ACCESS_ENUM = "VkAccessFlagBits2"
ALL_COMMANDS = "VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT"


def collect_bits(root, enum_name):
    bits, aliases = {}, {}

    def take(e):
        name = e.get("name")
        if e.get("alias"):
            aliases[name] = e.get("alias")
        elif e.get("bitpos") is not None:
            bits[name] = 1 << int(e.get("bitpos"))
        elif e.get("value") is not None:
            bits[name] = int(e.get("value"), 0)

    for enums in root.iter("enums"):
        if enums.get("name") == enum_name:
            for e in enums.iter("enum"):
                take(e)
    for e in root.iter("enum"):
        if e.get("extends") == enum_name:
            take(e)

    def resolve(name):
        seen = set()
        while name in aliases and name not in seen:
            seen.add(name)
            name = aliases[name]
        return name

    return bits, resolve


def split(attr):
    return [s for s in (attr or "").split(",") if s]


def main(vk_xml, out_path):
    root = ET.parse(vk_xml).getroot()
    stage_bits, stage_resolve = collect_bits(root, STAGE_ENUM)
    access_bits, access_resolve = collect_bits(root, ACCESS_ENUM)
    sync = root.find("sync")

    all_stages = 0
    for v in stage_bits.values():
        all_stages |= v

    stage_children = {}
    for s in sync.iter("syncstage"):
        name = stage_resolve(s.get("name"))
        eq = s.find("syncequivalent")
        stage_children[name] = [stage_resolve(c) for c in split(eq.get("stage") if eq is not None else None)]

    def expand_stage(name, seen=None):
        if name == ALL_COMMANDS:
            return all_stages
        seen = seen or set()
        if name in seen or name not in stage_bits:
            return 0
        seen.add(name)
        mask = stage_bits[name]
        for c in stage_children.get(name, []):
            mask |= expand_stage(c, seen)
        return mask

    access_support, access_children = {}, {}
    for a in sync.iter("syncaccess"):
        name = access_resolve(a.get("name"))
        sup = a.find("syncsupport")
        stages = split(sup.get("stage") if sup is not None else None)
        mask = 0
        for s in stages:
            mask |= expand_stage(stage_resolve(s))
        access_support[name] = mask if stages else all_stages
        eq = a.find("syncequivalent")
        access_children[name] = [access_resolve(c) for c in split(eq.get("access") if eq is not None else None)]

    reads = [n for n in access_bits if "_READ_" in n]
    writes = [n for n in access_bits if "_WRITE_" in n]
    access_children["VK_ACCESS_2_MEMORY_READ_BIT"] = reads
    access_children["VK_ACCESS_2_MEMORY_WRITE_BIT"] = writes

    def expand_access(name, seen=None):
        seen = seen or set()
        if name in seen or name not in access_bits:
            return 0
        seen.add(name)
        mask = access_bits[name]
        for c in access_children.get(name, []):
            mask |= expand_access(c, seen)
        return mask

    def rows(names, bits, fn):
        return "\n".join(f'\t\t{{0x{bits[n]:016x}ull, "{n}", 0x{fn(n):016x}ull}},' for n in sorted(names, key=lambda n: bits[n]) if bits[n])

    with open(out_path, "w") as f:
        f.write(f"""// generated by tests/gen_sync_tables.py from {vk_xml}, do not edit
#pragma once
#include <cstdint>

namespace mythril::sync_tables {{
	struct Entry {{
		uint64_t bit;
		const char* name;
		uint64_t mask;
	}};
	inline constexpr uint64_t kAllStages = 0x{all_stages:016x}ull;
	inline constexpr Entry kStageExpansion[] = {{
{rows(stage_bits.keys(), stage_bits, expand_stage)}
	}};
	inline constexpr Entry kAccessSupportedStages[] = {{
{rows([n for n in access_bits if n in access_support], access_bits, lambda n: access_support[n])}
	}};
	inline constexpr Entry kAccessExpansion[] = {{
{rows(access_bits.keys(), access_bits, expand_access)}
	}};
}}
""")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
